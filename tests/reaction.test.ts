import {test} from 'node:test';
import assert from 'node:assert/strict';
import {assess,upgradeEvaluation} from '../src/reaction';
test('Four marks separate learning judgment from NPC emotion and adapt old records without regrading',()=>{
 const base={outcome:'correct' as const,confidence:.95,native:false,emotion:'neutral' as const,reason:'상황에 맞는 설명'};
 assert.equal(assess({...base,reaction:'happy',goalAchieved:false}).progression,'advance');
 const soso=assess({...base,reaction:'neutral',goalAchieved:true});assert.equal(soso.mark,'△');assert.equal(soso.outcome,'correct');assert.equal(soso.progression,'advance');
 assert.equal(assess({...base,reaction:'neutral',goalAchieved:false}).progression,'retry');
 for(const reaction of ['angry','sad'] as const)assert.equal(assess({...base,reaction}).outcome,'misunderstanding');
 const unrelated=assess({...base,reaction:'confused',goalAchieved:true});assert.equal(unrelated.outcome,'clarify');assert.equal(unrelated.goalAchieved,false);
 assert.equal(unrelated.mark,'?');
 assert.equal(assess({...base,evaluationMark:'X',confidence:.3}).mark,'?');
 const native=assess({...base,evaluationMark:'O',native:true});assert.equal(native.mark,'△');assert.equal(native.outcome,'clarify');
 assert.equal(assess({...base,evaluationMark:'O',emotion:'sad'}).mark,'O');
 assert.equal(assess({...base,evaluationMark:'?',native:true}).mark,'?');
 assert.equal(assess({...base,evaluationMark:'X',native:true}).mark,'X');
 assert.equal(assess({...base,evaluationMark:'X',native:true}).outcome,'misunderstanding');
 assert.equal(assess({...base,evaluationMark:'X',native:true,confidence:.4}).mark,'?');
 assert.equal(assess({...base,evaluationMark:'O'}).policyVersion,'judgment-v3-draft');
 const historical=upgradeEvaluation({reaction:'sad',reason:'original',policyVersion:'reaction-v1-draft'}) as Record<string,unknown>;
 assert.equal(historical.mark,'X');assert.equal(historical.reason,'original');assert.equal(historical.policyVersion,'reaction-v1-draft');
});
